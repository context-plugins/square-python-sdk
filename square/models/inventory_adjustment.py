from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .enums.inventory_state import InventoryStateOrStr
from .inventory_adjustment_group import InventoryAdjustmentGroup, InventoryAdjustmentGroupDict
from .inventory_adjustment_reason_id import InventoryAdjustmentReasonId, InventoryAdjustmentReasonIdDict
from .money import Money, MoneyDict
from .source_application import SourceApplication, SourceApplicationDict


class InventoryAdjustment(SdkBaseModel):
    """Represents a change in state or quantity of product inventory at a particular time and location."""

    id: Optional[str] = UNSET
    """A unique ID generated by Square for the ``InventoryAdjustment``."""

    reference_id: OptionalNullable[str] = UNSET
    """An optional ID provided by the application to tie the ``InventoryAdjustment`` to an external system."""

    from_state: Optional[InventoryStateOrStr] = UNSET
    """Indicates the state of a tracked item quantity in the lifecycle of goods."""

    to_state: Optional[InventoryStateOrStr] = UNSET
    """Indicates the state of a tracked item quantity in the lifecycle of goods."""

    from_location_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Location <entity:Location>`__ where the related quantity of items is being
    tracked before the adjustment."""

    to_location_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Location <entity:Location>`__ where the related quantity of items is being
    tracked after the adjustment."""

    catalog_object_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `CatalogObject <entity:CatalogObject>`__ being tracked."""

    catalog_object_type: OptionalNullable[str] = UNSET
    """The `type <entity:CatalogObjectType>`__ of the `CatalogObject <entity:CatalogObject>`__ being tracked.

    The Inventory API supports setting and reading the ``"catalog_object_type": "ITEM_VARIATION"`` field value. In
    addition, it can also read the ``"catalog_object_type": "ITEM"`` field value that is set by the Square Restaurants
    app."""

    quantity: OptionalNullable[str] = UNSET
    """The number of items affected by the adjustment as a decimal string. Can support up to 5 digits after the decimal
    point."""

    total_price_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    occurred_at: OptionalNullable[str] = UNSET
    """A client-generated RFC 3339-formatted timestamp that indicates when the inventory adjustment took place. For
    inventory adjustment updates, the ``occurred_at`` timestamp cannot be older than 24 hours or in the future relative
    to the time of the request."""

    created_at: Optional[str] = UNSET
    """An RFC 3339-formatted timestamp that indicates when the inventory adjustment is received."""

    source: Optional[SourceApplication] = UNSET
    """Represents information about the application used to generate a change."""

    employee_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Employee <entity:Employee>`__ responsible for the inventory adjustment."""

    team_member_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Team Member <entity:TeamMember>`__ responsible for the inventory adjustment."""

    transaction_id: Optional[str] = UNSET
    """The Square-generated ID of the `Transaction <entity:Transaction>`__ that caused the adjustment. Only relevant for
    payment-related state transitions."""

    refund_id: Optional[str] = UNSET
    """The Square-generated ID of the `Refund <entity:Refund>`__ that caused the adjustment. Only relevant for
    refund-related state transitions."""

    purchase_order_id: Optional[str] = UNSET
    """The Square-generated ID of the purchase order that caused the adjustment. Only relevant for state transitions
    from the Square for Retail app."""

    goods_receipt_id: Optional[str] = UNSET
    """The Square-generated ID of the goods receipt that caused the adjustment. Only relevant for state transitions from
    the Square for Retail app."""

    adjustment_group: Optional[InventoryAdjustmentGroup] = UNSET
    cost_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    vendor_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the Vendor from which the merchant purchased this product. This field is only
    applicable for stock receive adjustments that introduce stock into the system (from_state is NONE or
    UNLINKED_RETURN). This field will only accept writes if the merchant has an active subscription for either Retail
    Plus, Restaurants Plus, or Restaurants Premium."""

    physical_count_id: Optional[str] = UNSET
    """The Square-generated ID of the InventoryPhysicalCount (recount) that generated this adjustment, if applicable.
    The quantity of an adjustment generated by a physical count cannot be edited."""

    reason_id: Optional[InventoryAdjustmentReasonId] = UNSET
    """Identifies a standard or custom inventory adjustment reason."""


class InventoryAdjustmentDict(TypedDict):
    id: NotRequired[str]
    reference_id: NotRequired[str | None]
    from_state: NotRequired[InventoryStateOrStr]
    to_state: NotRequired[InventoryStateOrStr]
    from_location_id: NotRequired[str | None]
    to_location_id: NotRequired[str | None]
    catalog_object_id: NotRequired[str | None]
    catalog_object_type: NotRequired[str | None]
    quantity: NotRequired[str | None]
    total_price_money: NotRequired[MoneyDict]
    occurred_at: NotRequired[str | None]
    created_at: NotRequired[str]
    source: NotRequired[SourceApplicationDict]
    employee_id: NotRequired[str | None]
    team_member_id: NotRequired[str | None]
    transaction_id: NotRequired[str]
    refund_id: NotRequired[str]
    purchase_order_id: NotRequired[str]
    goods_receipt_id: NotRequired[str]
    adjustment_group: NotRequired[InventoryAdjustmentGroupDict]
    cost_money: NotRequired[MoneyDict]
    vendor_id: NotRequired[str | None]
    physical_count_id: NotRequired[str]
    reason_id: NotRequired[InventoryAdjustmentReasonIdDict]
