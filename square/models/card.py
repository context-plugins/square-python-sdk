from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .address import Address, AddressDict
from .enums.card_brand import CardBrandOrStr
from .enums.card_co_brand import CardCoBrandOrStr
from .enums.card_issuer_alert import CardIssuerAlertOrStr
from .enums.card_prepaid_type import CardPrepaidTypeOrStr
from .enums.card_type import CardTypeOrStr


class Card(SdkBaseModel):
    """Represents the payment details of a card to be used for payments. These details are determined by the payment
    token generated by Web Payments SDK."""

    id: Optional[str] = UNSET
    """Unique ID for this card. Generated by Square."""

    card_brand: Optional[CardBrandOrStr] = UNSET
    """Indicates a card's brand, such as ``VISA`` or ``MASTERCARD``."""

    last_4: Optional[str] = UNSET
    """The last 4 digits of the card number."""

    exp_month: OptionalNullable[int] = UNSET
    """The expiration month of the associated card as an integer between 1 and 12."""

    exp_year: OptionalNullable[int] = UNSET
    """The four-digit year of the card's expiration date."""

    cardholder_name: OptionalNullable[str] = UNSET
    """The name of the cardholder."""

    billing_address: Optional[Address] = UNSET
    """Represents a postal address in a country. For more information, see `Working with Addresses
    <https://developer.squareup.com/docs/build-basics/working-with-addresses>`__."""

    fingerprint: Optional[str] = UNSET
    """Intended as a Square-assigned identifier, based on the card number, to identify the card across multiple
    locations within a single application."""

    customer_id: OptionalNullable[str] = UNSET
    """**Required** The ID of a `customer <entity:Customer>`__ to be associated with the card."""

    merchant_id: Optional[str] = UNSET
    """The ID of the merchant associated with the card."""

    reference_id: OptionalNullable[str] = UNSET
    """An optional user-defined reference ID that associates this card with another entity in an external system. For
    example, a customer ID from an external customer management system."""

    enabled: Optional[bool] = UNSET
    """Indicates whether or not a card can be used for payments."""

    card_type: Optional[CardTypeOrStr] = UNSET
    """Indicates a card's type, such as ``CREDIT`` or ``DEBIT``."""

    prepaid_type: Optional[CardPrepaidTypeOrStr] = UNSET
    """Indicates a card's prepaid type, such as ``NOT_PREPAID`` or ``PREPAID``."""

    bin: Optional[str] = UNSET
    """The first six digits of the card number, known as the Bank Identification Number (BIN). Only the Payments API
    returns this field."""

    created_at: Optional[str] = UNSET
    """Timestamp for when the card object was created on Square’s servers. In RFC 3339 format, e.g.,
    "2016-09-04T23:59:33.123Z"."""

    disabled_at: Optional[str] = UNSET
    """Timestamp for when the card object was disabled on Square’s servers. In RFC 3339 format, e.g.,
    "2016-09-04T23:59:33.123Z"."""

    version: Optional[int] = UNSET
    """Current version number of the card. Increments with each card update. Requests to update an existing Card object
    will be rejected unless the version in the request matches the current version for the Card."""

    card_co_brand: Optional[CardCoBrandOrStr] = UNSET
    """Indicates the brand for a co-branded card."""

    issuer_alert: Optional[CardIssuerAlertOrStr] = UNSET
    """Indicates the type of issuer alert for a `card on file <entity:Card>`__."""

    issuer_alert_at: Optional[str] = UNSET
    """The timestamp of when the current issuer alert was received and processed, in RFC 3339 format.

    This field is present only if there's an active issuer alert."""

    hsa_fsa: Optional[bool] = UNSET
    """Indicates whether the card is linked to a Health Savings Account (HSA) or Flexible Spending Account (FSA), based
    on the card BIN."""


class CardDict(TypedDict):
    id: NotRequired[str]
    card_brand: NotRequired[CardBrandOrStr]
    last_4: NotRequired[str]
    exp_month: NotRequired[int | None]
    exp_year: NotRequired[int | None]
    cardholder_name: NotRequired[str | None]
    billing_address: NotRequired[AddressDict]
    fingerprint: NotRequired[str]
    customer_id: NotRequired[str | None]
    merchant_id: NotRequired[str]
    reference_id: NotRequired[str | None]
    enabled: NotRequired[bool]
    card_type: NotRequired[CardTypeOrStr]
    prepaid_type: NotRequired[CardPrepaidTypeOrStr]
    bin: NotRequired[str]
    created_at: NotRequired[str]
    disabled_at: NotRequired[str]
    version: NotRequired[int]
    card_co_brand: NotRequired[CardCoBrandOrStr]
    issuer_alert: NotRequired[CardIssuerAlertOrStr]
    issuer_alert_at: NotRequired[str]
    hsa_fsa: NotRequired[bool]
