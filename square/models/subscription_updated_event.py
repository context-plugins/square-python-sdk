from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .subscription_updated_event_data import SubscriptionUpdatedEventData, SubscriptionUpdatedEventDataDict


class SubscriptionUpdatedEvent(SdkBaseModel):
    """Published when a `Subscription <entity:Subscription>`__ is updated. Typically the ``subscription.status`` is
    updated as subscriptions become active or cancelled."""

    merchant_id: OptionalNullable[str] = UNSET
    """The ID of the target merchant associated with the event."""

    type_: OptionalNullable[str] = Field(default=UNSET, alias="type")
    """The type of event this represents, ``"subscription.updated"``."""

    event_id: OptionalNullable[str] = UNSET
    """A unique ID for the event."""

    created_at: Optional[str] = UNSET
    """Timestamp of when the event was created, in RFC 3339 format."""

    data: Optional[SubscriptionUpdatedEventData] = UNSET


class SubscriptionUpdatedEventDict(TypedDict):
    merchant_id: NotRequired[str | None]
    type_: NotRequired[str | None]
    event_id: NotRequired[str | None]
    created_at: NotRequired[str]
    data: NotRequired[SubscriptionUpdatedEventDataDict]
