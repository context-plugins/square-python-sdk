from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .card import Card, CardDict
from .card_payment_timeline import CardPaymentTimeline, CardPaymentTimelineDict
from .card_surcharge_details import CardSurchargeDetails, CardSurchargeDetailsDict
from .device_details import DeviceDetails, DeviceDetailsDict
from .error import Error, ErrorDict


class CardPaymentDetails(SdkBaseModel):
    """Reflects the current status of a card payment. Contains only non-confidential information."""

    status: Optional[str] = UNSET
    """The card payment's current state. The state can be AUTHORIZED, CAPTURED, VOIDED, or FAILED."""

    card: Optional[Card] = UNSET
    """Represents the payment details of a card to be used for payments. These details are determined by the payment
    token generated by Web Payments SDK."""

    entry_method: Optional[str] = UNSET
    """The method used to enter the card's details for the payment. The method can be ``KEYED``, ``SWIPED``, ``EMV``,
    ``ON_FILE``, or ``CONTACTLESS``."""

    cvv_status: Optional[str] = UNSET
    """The status code returned from the Card Verification Value (CVV) check. The code can be ``CVV_ACCEPTED``,
    ``CVV_REJECTED``, or ``CVV_NOT_CHECKED``."""

    avs_status: Optional[str] = UNSET
    """The status code returned from the Address Verification System (AVS) check. The code can be ``AVS_ACCEPTED``,
    ``AVS_REJECTED``, or ``AVS_NOT_CHECKED``."""

    auth_result_code: Optional[str] = UNSET
    """The status code returned by the card issuer that describes the payment's authorization status."""

    application_identifier: Optional[str] = UNSET
    """For EMV payments, the application ID identifies the EMV application used for the payment."""

    application_name: Optional[str] = UNSET
    """For EMV payments, the human-readable name of the EMV application used for the payment."""

    application_cryptogram: Optional[str] = UNSET
    """For EMV payments, the cryptogram generated for the payment."""

    verification_method: Optional[str] = UNSET
    """For EMV payments, the method used to verify the cardholder's identity. The method can be ``PIN``, ``SIGNATURE``,
    ``PIN_AND_SIGNATURE``, ``ON_DEVICE``, or ``NONE``."""

    verification_results: Optional[str] = UNSET
    """For EMV payments, the results of the cardholder verification. The result can be ``SUCCESS``, ``FAILURE``, or
    ``UNKNOWN``."""

    statement_description: Optional[str] = UNSET
    """The statement description sent to the card networks.

    Note: The actual statement description varies and is likely to be truncated and appended with additional information
    on a per issuer basis."""

    device_details: Optional[DeviceDetails] = UNSET
    """Details about the device that took the payment."""

    card_payment_timeline: Optional[CardPaymentTimeline] = UNSET
    """The timeline for card payments."""

    refund_requires_card_presence: Optional[bool] = UNSET
    """Whether the card must be physically present for the payment to be refunded. If set to ``true``, the card must be
    present."""

    errors: Optional[list[Error]] = UNSET
    """Information about errors encountered during the request."""

    applied_card_surcharge_details: Optional[CardSurchargeDetails] = UNSET
    """Details related to an attempt to apply a card surcharge to this payment. When surcharge eligibility is not known
    in advance, such as when the card type (debit or credit) is required to make the eligibility determination,
    proposed_card_surcharge_money and proposed_additional_amount_money will match the values in the request, while
    card_surcharge_money and additional_amount_money are present only when the payment has a surcharge applied."""

    wallet_type: Optional[str] = UNSET
    """The type of digital wallet used for this card payment, if applicable. Currently only populated for in-person
    Apple Pay payments. Detection has no false positives but may have false negatives (some Apple Pay payments may not
    be detected).

    For payments with ``source_type`` of ``WALLET``, see ``DigitalWalletDetails`` instead.

    Values: ``APPLE_PAY``"""


class CardPaymentDetailsDict(TypedDict):
    status: NotRequired[str]
    card: NotRequired[CardDict]
    entry_method: NotRequired[str]
    cvv_status: NotRequired[str]
    avs_status: NotRequired[str]
    auth_result_code: NotRequired[str]
    application_identifier: NotRequired[str]
    application_name: NotRequired[str]
    application_cryptogram: NotRequired[str]
    verification_method: NotRequired[str]
    verification_results: NotRequired[str]
    statement_description: NotRequired[str]
    device_details: NotRequired[DeviceDetailsDict]
    card_payment_timeline: NotRequired[CardPaymentTimelineDict]
    refund_requires_card_presence: NotRequired[bool]
    errors: NotRequired[list[ErrorDict]]
    applied_card_surcharge_details: NotRequired[CardSurchargeDetailsDict]
    wallet_type: NotRequired[str]
