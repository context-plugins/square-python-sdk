from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .enums.inventory_state import InventoryStateOrStr
from .source_application import SourceApplication, SourceApplicationDict


class InventoryPhysicalCount(SdkBaseModel):
    """Represents the quantity of an item variation that is physically present at a specific location, verified by a
    seller or a seller's employee. For example, a physical count might come from an employee counting the item
    variations on hand or from syncing with an external system."""

    id: Optional[str] = UNSET
    """A unique Square-generated ID for the `InventoryPhysicalCount <entity:InventoryPhysicalCount>`__."""

    reference_id: OptionalNullable[str] = UNSET
    """An optional ID provided by the application to tie the `InventoryPhysicalCount <entity:InventoryPhysicalCount>`__
    to an external system."""

    catalog_object_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `CatalogObject <entity:CatalogObject>`__ being tracked."""

    catalog_object_type: OptionalNullable[str] = UNSET
    """The `type <entity:CatalogObjectType>`__ of the `CatalogObject <entity:CatalogObject>`__ being tracked.

    The Inventory API supports setting and reading the ``"catalog_object_type": "ITEM_VARIATION"`` field value. In
    addition, it can also read the ``"catalog_object_type": "ITEM"`` field value that is set by the Square Restaurants
    app."""

    state: Optional[InventoryStateOrStr] = UNSET
    """Indicates the state of a tracked item quantity in the lifecycle of goods."""

    location_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Location <entity:Location>`__ where the related quantity of items is being
    tracked."""

    quantity: OptionalNullable[str] = UNSET
    """The number of items affected by the physical count as a decimal string. The number can support up to 5 digits
    after the decimal point."""

    source: Optional[SourceApplication] = UNSET
    """Represents information about the application used to generate a change."""

    employee_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Employee <entity:Employee>`__ responsible for the physical count."""

    team_member_id: OptionalNullable[str] = UNSET
    """The Square-generated ID of the `Team Member <entity:TeamMember>`__ responsible for the physical count."""

    occurred_at: OptionalNullable[str] = UNSET
    """A client-generated RFC 3339-formatted timestamp that indicates when the physical count was examined. For physical
    count updates, the ``occurred_at`` timestamp cannot be older than 24 hours or in the future relative to the time of
    the request."""

    created_at: Optional[str] = UNSET
    """An RFC 3339-formatted timestamp that indicates when the physical count is received."""

    adjustment_id: Optional[str] = UNSET
    """The Square-generated ID of the InventoryAdjustment that was generated by this physical count in order to adjust
    the current stock count to reflect the re-counted quantity. This field may be empty if the merchant does not have an
    active subscription for either Retail Plus, Restaurants Plus, or Restaurants Premium."""


class InventoryPhysicalCountDict(TypedDict):
    id: NotRequired[str]
    reference_id: NotRequired[str | None]
    catalog_object_id: NotRequired[str | None]
    catalog_object_type: NotRequired[str | None]
    state: NotRequired[InventoryStateOrStr]
    location_id: NotRequired[str | None]
    quantity: NotRequired[str | None]
    source: NotRequired[SourceApplication | SourceApplicationDict]
    employee_id: NotRequired[str | None]
    team_member_id: NotRequired[str | None]
    occurred_at: NotRequired[str | None]
    created_at: NotRequired[str]
    adjustment_id: NotRequired[str]
