from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .device_checkout_options import DeviceCheckoutOptions, DeviceCheckoutOptionsDict
from .enums.action_cancel_reason import ActionCancelReasonOrStr
from .enums.checkout_options_payment_type import CheckoutOptionsPaymentTypeOrStr
from .money import Money, MoneyDict
from .payment_options import PaymentOptions, PaymentOptionsDict


class TerminalCheckout(SdkBaseModel):
    """Represents a checkout processed by the Square Terminal."""

    id: Optional[str] = UNSET
    """A unique ID for this ``TerminalCheckout``."""

    amount_money: Money
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    reference_id: OptionalNullable[str] = UNSET
    """An optional user-defined reference ID that can be used to associate this ``TerminalCheckout`` to another entity
    in an external system. For example, an order ID generated by a third-party shopping cart. The ID is also associated
    with any payments used to complete the checkout."""

    note: OptionalNullable[str] = UNSET
    """An optional note to associate with the checkout, as well as with any payments used to complete the checkout.
    Note: maximum 500 characters"""

    order_id: OptionalNullable[str] = UNSET
    """The reference to the Square order ID for the checkout request."""

    payment_options: Optional[PaymentOptions] = UNSET
    device_options: DeviceCheckoutOptions
    deadline_duration: OptionalNullable[str] = UNSET
    """An RFC 3339 duration, after which the checkout is automatically canceled. A ``TerminalCheckout`` that is
    ``PENDING`` is automatically ``CANCELED`` and has a cancellation reason of ``TIMED_OUT``.

    Default: 5 minutes from creation

    Maximum: 5 minutes"""

    status: Optional[str] = UNSET
    """The status of the ``TerminalCheckout``. Options: ``PENDING``, ``IN_PROGRESS``, ``CANCEL_REQUESTED``,
    ``CANCELED``, ``COMPLETED``"""

    cancel_reason: Optional[ActionCancelReasonOrStr] = UNSET
    payment_ids: Optional[list[str]] = UNSET
    """A list of IDs for payments created by this ``TerminalCheckout``."""

    created_at: Optional[str] = UNSET
    """The time when the ``TerminalCheckout`` was created, as an RFC 3339 timestamp."""

    updated_at: Optional[str] = UNSET
    """The time when the ``TerminalCheckout`` was last updated, as an RFC 3339 timestamp."""

    app_id: Optional[str] = UNSET
    """The ID of the application that created the checkout."""

    location_id: Optional[str] = UNSET
    """The location of the device where the ``TerminalCheckout`` was directed."""

    payment_type: Optional[CheckoutOptionsPaymentTypeOrStr] = UNSET
    team_member_id: OptionalNullable[str] = UNSET
    """An optional ID of the team member associated with creating the checkout."""

    customer_id: OptionalNullable[str] = UNSET
    """An optional ID of the customer associated with the checkout."""

    app_fee_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    statement_description_identifier: OptionalNullable[str] = UNSET
    """Optional additional payment information to include on the customer's card statement as part of the statement
    description. This can be, for example, an invoice number, ticket number, or short description that uniquely
    identifies the purchase."""

    tip_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""


class TerminalCheckoutDict(TypedDict):
    id: NotRequired[str]
    amount_money: MoneyDict
    reference_id: NotRequired[str | None]
    note: NotRequired[str | None]
    order_id: NotRequired[str | None]
    payment_options: NotRequired[PaymentOptionsDict]
    device_options: DeviceCheckoutOptionsDict
    deadline_duration: NotRequired[str | None]
    status: NotRequired[str]
    cancel_reason: NotRequired[ActionCancelReasonOrStr]
    payment_ids: NotRequired[list[str]]
    created_at: NotRequired[str]
    updated_at: NotRequired[str]
    app_id: NotRequired[str]
    location_id: NotRequired[str]
    payment_type: NotRequired[CheckoutOptionsPaymentTypeOrStr]
    team_member_id: NotRequired[str | None]
    customer_id: NotRequired[str | None]
    app_fee_money: NotRequired[MoneyDict]
    statement_description_identifier: NotRequired[str | None]
    tip_money: NotRequired[MoneyDict]
