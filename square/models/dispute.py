from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .disputed_payment import DisputedPayment, DisputedPaymentDict
from .enums.card_brand import CardBrandOrStr
from .enums.dispute_reason import DisputeReasonOrStr
from .enums.dispute_state import DisputeStateOrStr
from .money import Money, MoneyDict


class Dispute(SdkBaseModel):
    """Represents a `dispute <https://developer.squareup.com/docs/disputes-api/overview>`__ a cardholder initiated with
    their bank."""

    dispute_id: OptionalNullable[str] = UNSET
    """The unique ID for this ``Dispute``, generated by Square."""

    id: Optional[str] = UNSET
    """The unique ID for this ``Dispute``, generated by Square."""

    amount_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    reason: Optional[DisputeReasonOrStr] = UNSET
    """The list of possible reasons why a cardholder might initiate a dispute with their bank."""

    state: Optional[DisputeStateOrStr] = UNSET
    """The list of possible dispute states."""

    due_at: OptionalNullable[str] = UNSET
    """The deadline by which the seller must respond to the dispute, in `RFC 3339 format
    <https://developer.squareup.com/docs/build-basics/common-data-types/working-with-dates>`__."""

    disputed_payment: Optional[DisputedPayment] = UNSET
    """The payment the cardholder disputed."""

    evidence_ids: Optional[list[str | None]] = UNSET
    """The IDs of the evidence associated with the dispute."""

    card_brand: Optional[CardBrandOrStr] = UNSET
    """Indicates a card's brand, such as ``VISA`` or ``MASTERCARD``."""

    created_at: Optional[str] = UNSET
    """The timestamp when the dispute was created, in RFC 3339 format."""

    updated_at: Optional[str] = UNSET
    """The timestamp when the dispute was last updated, in RFC 3339 format."""

    brand_dispute_id: OptionalNullable[str] = UNSET
    """The ID of the dispute in the card brand system, generated by the card brand."""

    reported_date: OptionalNullable[str] = UNSET
    """The timestamp when the dispute was reported, in RFC 3339 format."""

    reported_at: OptionalNullable[str] = UNSET
    """The timestamp when the dispute was reported, in RFC 3339 format."""

    version: Optional[int] = UNSET
    """The current version of the ``Dispute``."""

    location_id: OptionalNullable[str] = UNSET
    """The ID of the location where the dispute originated."""


class DisputeDict(TypedDict):
    dispute_id: NotRequired[str | None]
    id: NotRequired[str]
    amount_money: NotRequired[Money | MoneyDict]
    reason: NotRequired[DisputeReasonOrStr]
    state: NotRequired[DisputeStateOrStr]
    due_at: NotRequired[str | None]
    disputed_payment: NotRequired[DisputedPayment | DisputedPaymentDict]
    evidence_ids: NotRequired[list[str | None]]
    card_brand: NotRequired[CardBrandOrStr]
    created_at: NotRequired[str]
    updated_at: NotRequired[str]
    brand_dispute_id: NotRequired[str | None]
    reported_date: NotRequired[str | None]
    reported_at: NotRequired[str | None]
    version: NotRequired[int]
    location_id: NotRequired[str | None]
