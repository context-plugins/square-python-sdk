from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .card import Card, CardDict


class DestinationDetailsCardRefundDetails(SdkBaseModel):
    card: Optional[Card] = UNSET
    """Represents the payment details of a card to be used for payments. These details are determined by the payment
    token generated by Web Payments SDK."""

    entry_method: OptionalNullable[str] = UNSET
    """The method used to enter the card's details for the refund. The method can be ``KEYED``, ``SWIPED``, ``EMV``,
    ``ON_FILE``, or ``CONTACTLESS``."""

    auth_result_code: OptionalNullable[str] = UNSET
    """The authorization code provided by the issuer when a refund is approved."""


class DestinationDetailsCardRefundDetailsDict(TypedDict):
    card: NotRequired[CardDict]
    entry_method: NotRequired[str | None]
    auth_result_code: NotRequired[str | None]
