class OrderLineItemTax(SdkBaseModel):
    """Represents a tax that applies to one or more line item in the order.

    Fixed-amount, order-scoped taxes are distributed across all non-zero line item totals. The amount distributed to
    each line item is relative to the amount the item contributes to the order subtotal."""

    uid: OptionalNullable[str] = UNSET
    """A unique ID that identifies the tax only within this order."""

    catalog_object_id: OptionalNullable[str] = UNSET
    """The catalog object ID referencing `CatalogTax <entity:CatalogTax>`__."""

    catalog_version: OptionalNullable[int] = UNSET
    """The version of the catalog object that this tax references."""

    name: OptionalNullable[str] = UNSET
    """The tax's name."""

    type_: Optional[OrderLineItemTaxTypeOrStr] = Field(default=UNSET, alias="type")
    """Indicates how the tax is applied to the associated line item or order."""

    percentage: OptionalNullable[str] = UNSET
    """The percentage of the tax, as a string representation of a decimal number. For example, a value of ``"7.25"``
    corresponds to a percentage of 7.25%."""

    metadata: OptionalNullable[dict[str, str]] = UNSET
    """Application-defined data attached to this tax. Metadata fields are intended to store descriptive references or
    associations with an entity in another system or store brief information about the object. Square does not process
    this field; it only stores and returns it in relevant API calls. Do not use metadata to store any sensitive
    information (such as personally identifiable information or card details).

    Keys written by applications must be 60 characters or less and must be in the character set ``[a-zA-Z0-9_-]``.
    Entries can also include metadata generated by Square. These keys are prefixed with a namespace, separated from the
    key with a ':' character.

    Values have a maximum length of 255 characters.

    An application can have up to 10 entries per metadata field.

    Entries written by applications are private and can only be read or modified by the same application.

    For more information, see `Metadata <https://developer.squareup.com/docs/build-basics/metadata>`__."""

    applied_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    scope: Optional[OrderLineItemTaxScopeOrStr] = UNSET
    """Indicates whether this is a line-item or order-level tax."""

    auto_applied: Optional[bool] = UNSET
    """Determines whether the tax was automatically applied to the order based on the catalog configuration. For an
    example, see `Automatically Apply Taxes to an Order
    <https://developer.squareup.com/docs/orders-api/apply-taxes-and-discounts/auto-apply-taxes>`__."""


