from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, OptionalNullable, SdkBaseModel
from .address import Address, AddressDict
from .enums.transaction_product import TransactionProductOrStr
from .refund import Refund, RefundDict
from .tender import Tender, TenderDict


class Transaction(SdkBaseModel):
    """Represents a transaction processed with Square, either with the Connect API or with Square Point of Sale.

    The ``tenders`` field of this object lists all methods of payment used to pay in the transaction."""

    id: Optional[str] = UNSET
    """The transaction's unique ID, issued by Square payments servers."""

    location_id: OptionalNullable[str] = UNSET
    """The ID of the transaction's associated location."""

    created_at: Optional[str] = UNSET
    """The timestamp for when the transaction was created, in RFC 3339 format."""

    tenders: Optional[list[Tender | None]] = UNSET
    """The tenders used to pay in the transaction."""

    refunds: Optional[list[Refund | None]] = UNSET
    """Refunds that have been applied to any tender in the transaction."""

    reference_id: OptionalNullable[str] = UNSET
    """If the transaction was created with the `Charge <api-endpoint:Transactions-Charge>`__ endpoint, this value is the
    same as the value provided for the ``reference_id`` parameter in the request to that endpoint. Otherwise, it is not
    set."""

    product: Optional[TransactionProductOrStr] = UNSET
    """Indicates the Square product used to process a transaction."""

    client_id: OptionalNullable[str] = UNSET
    """If the transaction was created in the Square Point of Sale app, this value is the ID generated for the
    transaction by Square Point of Sale.

    This ID has no relationship to the transaction's canonical ``id``, which is generated by Square's backend servers.
    This value is generated for bookkeeping purposes, in case the transaction cannot immediately be completed (for
    example, if the transaction is processed in offline mode).

    It is not currently possible with the Connect API to perform a transaction lookup by this value."""

    shipping_address: Optional[Address] = UNSET
    """Represents a postal address in a country. For more information, see `Working with Addresses
    <https://developer.squareup.com/docs/build-basics/working-with-addresses>`__."""

    order_id: OptionalNullable[str] = UNSET
    """The order_id is an identifier for the order associated with this transaction, if any."""


class TransactionDict(TypedDict):
    id: NotRequired[str]
    location_id: NotRequired[str | None]
    created_at: NotRequired[str]
    tenders: NotRequired[list[Tender | TenderDict | None]]
    refunds: NotRequired[list[Refund | RefundDict | None]]
    reference_id: NotRequired[str | None]
    product: NotRequired[TransactionProductOrStr]
    client_id: NotRequired[str | None]
    shipping_address: NotRequired[Address | AddressDict]
    order_id: NotRequired[str | None]
