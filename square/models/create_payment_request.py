from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .address import Address, AddressDict
from .cash_payment_details import CashPaymentDetails, CashPaymentDetailsDict
from .customer_details import CustomerDetails, CustomerDetailsDict
from .external_payment_details import ExternalPaymentDetails, ExternalPaymentDetailsDict
from .money import Money, MoneyDict
from .offline_payment_details import OfflinePaymentDetails, OfflinePaymentDetailsDict


class CreatePaymentRequest(SdkBaseModel):
    """Describes a request to create a payment using `CreatePayment <api-endpoint:Payments-CreatePayment>`__."""

    source_id: str
    """The ID for the source of funds for this payment. This could be a payment token generated by the Web Payments SDK
    for any of its `supported methods
    <https://developer.squareup.com/docs/web-payments/overview#explore-payment-methods>`__, including cards, bank
    transfers, Afterpay or Cash App Pay. If recording a payment that the seller received outside of Square, specify
    either "CASH" or "EXTERNAL". For more information, see `Take Payments
    <https://developer.squareup.com/docs/payments-api/take-payments>`__."""

    idempotency_key: str
    """A unique string that identifies this ``CreatePayment`` request. Keys can be any valid string but must be unique
    for every ``CreatePayment`` request.

    Note: The number of allowed characters might be less than the stated maximum, if multi-byte characters are used.

    For more information, see `Idempotency <https://developer.squareup.com/docs/working-with-apis/idempotency>`__."""

    amount_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    tip_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    app_fee_money: Optional[Money] = UNSET
    """Represents an amount of money. ``Money`` fields can be signed or unsigned. Fields that do not explicitly define
    whether they are signed or unsigned are considered unsigned and can only hold positive amounts. For signed fields,
    the sign of the value indicates the purpose of the money transfer. See `Working with Monetary Amounts
    <https://developer.squareup.com/docs/build-basics/working-with-monetary-amounts>`__ for more information."""

    delay_duration: Optional[str] = UNSET
    """The duration of time after the payment's creation when Square automatically either completes or cancels the
    payment depending on the ``delay_action`` field value. For more information, see `Time threshold
    <https://developer.squareup.com/docs/payments-api/take-payments/card-payments/delayed-capture#time-threshold>`__.

    This parameter should be specified as a time duration, in RFC 3339 format.

    Note: This feature is only supported for card payments. This parameter can only be set for a delayed capture payment
    (``autocomplete=false``).

    Default:

    - Card-present payments: "PT36H" (36 hours) from the creation time.
    - Card-not-present payments: "P7D" (7 days) from the creation time."""

    delay_action: Optional[str] = UNSET
    """The action to be applied to the payment when the ``delay_duration`` has elapsed. The action must be CANCEL or
    COMPLETE. For more information, see `Time Threshold
    <https://developer.squareup.com/docs/payments-api/take-payments/card-payments/delayed-capture#time-threshold>`__.

    Default: CANCEL"""

    autocomplete: Optional[bool] = UNSET
    """If set to ``true``, this payment will be completed when possible. If set to ``false``, this payment is held in an
    approved state until either explicitly completed (captured) or canceled (voided). For more information, see `Delayed
    capture
    <https://developer.squareup.com/docs/payments-api/take-payments/card-payments#delayed-capture-of-a-card-payment>`__.

    Default: true"""

    order_id: Optional[str] = UNSET
    """Associates a previously created order with this payment."""

    customer_id: Optional[str] = UNSET
    """The `Customer <entity:Customer>`__ ID of the customer associated with the payment.

    This is required if the ``source_id`` refers to a card on file created using the Cards API."""

    location_id: Optional[str] = UNSET
    """The location ID to associate with the payment. If not specified, the `main location
    <https://developer.squareup.com/docs/locations-api#about-the-main-location>`__ is used."""

    team_member_id: Optional[str] = UNSET
    """An optional `TeamMember <entity:TeamMember>`__ ID to associate with this payment."""

    reference_id: Optional[str] = UNSET
    """A user-defined ID to associate with the payment.

    You can use this field to associate the payment to an entity in an external system (for example, you might specify
    an order ID that is generated by a third-party shopping cart)."""

    verification_token: Optional[str] = UNSET
    """An identifying token generated by `payments.verifyBuyer()
    <https://developer.squareup.com/reference/sdks/web/payments/objects/Payments#Payments.verifyBuyer>`__. Verification
    tokens encapsulate customer device information and 3-D Secure challenge results to indicate that Square has verified
    the buyer identity.

    For more information, see `SCA Overview <https://developer.squareup.com/docs/sca-overview>`__."""

    accept_partial_authorization: Optional[bool] = UNSET
    """If set to ``true`` and charging a Square Gift Card, a payment might be returned with ``amount_money`` equal to
    less than what was requested. For example, a request for $20 when charging a Square Gift Card with a balance of $5
    results in an APPROVED payment of $5. You might choose to prompt the buyer for an additional payment to cover the
    remainder or cancel the Gift Card payment. This field cannot be ``true`` when ``autocomplete = true``.

    For more information, see `Partial amount with Square Gift Cards
    <https://developer.squareup.com/docs/payments-api/take-payments#partial-payment-gift-card>`__.

    Default: false"""

    buyer_email_address: Optional[str] = UNSET
    """The buyer's email address."""

    buyer_phone_number: Optional[str] = UNSET
    """The buyer's phone number. Must follow the following format:
    1. A leading + symbol (followed by a country code)
    2. The phone number can contain spaces and the special characters ``(`` , ``)`` , ``-`` , and ``.``.
    Alphabetical characters aren't allowed.
    3. The phone number must contain between 9 and 16 digits."""

    billing_address: Optional[Address] = UNSET
    """Represents a postal address in a country. For more information, see `Working with Addresses
    <https://developer.squareup.com/docs/build-basics/working-with-addresses>`__."""

    shipping_address: Optional[Address] = UNSET
    """Represents a postal address in a country. For more information, see `Working with Addresses
    <https://developer.squareup.com/docs/build-basics/working-with-addresses>`__."""

    note: Optional[str] = UNSET
    """An optional note to be entered by the developer when creating a payment."""

    statement_description_identifier: Optional[str] = UNSET
    """Optional additional payment information to include on the customer's card statement as part of the statement
    description. This can be, for example, an invoice number, ticket number, or short description that uniquely
    identifies the purchase.

    Note that the ``statement_description_identifier`` might get truncated on the statement description to fit the
    required information including the Square identifier (SQ *) and name of the seller taking the payment."""

    cash_details: Optional[CashPaymentDetails] = UNSET
    """Stores details about a cash payment. Contains only non-confidential information. For more information, see `Take
    Cash Payments <https://developer.squareup.com/docs/payments-api/take-payments/cash-payments>`__."""

    external_details: Optional[ExternalPaymentDetails] = UNSET
    """Stores details about an external payment. Contains only non-confidential information. For more information, see
    `Take External Payments <https://developer.squareup.com/docs/payments-api/take-payments/external-payments>`__."""

    customer_details: Optional[CustomerDetails] = UNSET
    """Details about the customer making the payment."""

    offline_payment_details: Optional[OfflinePaymentDetails] = UNSET
    """Details specific to offline payments."""


class CreatePaymentRequestDict(TypedDict):
    source_id: str
    idempotency_key: str
    amount_money: NotRequired[MoneyDict]
    tip_money: NotRequired[MoneyDict]
    app_fee_money: NotRequired[MoneyDict]
    delay_duration: NotRequired[str]
    delay_action: NotRequired[str]
    autocomplete: NotRequired[bool]
    order_id: NotRequired[str]
    customer_id: NotRequired[str]
    location_id: NotRequired[str]
    team_member_id: NotRequired[str]
    reference_id: NotRequired[str]
    verification_token: NotRequired[str]
    accept_partial_authorization: NotRequired[bool]
    buyer_email_address: NotRequired[str]
    buyer_phone_number: NotRequired[str]
    billing_address: NotRequired[AddressDict]
    shipping_address: NotRequired[AddressDict]
    note: NotRequired[str]
    statement_description_identifier: NotRequired[str]
    cash_details: NotRequired[CashPaymentDetailsDict]
    external_details: NotRequired[ExternalPaymentDetailsDict]
    customer_details: NotRequired[CustomerDetailsDict]
    offline_payment_details: NotRequired[OfflinePaymentDetailsDict]
