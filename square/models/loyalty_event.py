from __future__ import annotations

from pydantic import Field
from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .enums.loyalty_event_source import LoyaltyEventSourceOrStr
from .enums.loyalty_event_type import LoyaltyEventTypeOrStr
from .loyalty_event_accumulate_points import LoyaltyEventAccumulatePoints, LoyaltyEventAccumulatePointsDict
from .loyalty_event_accumulate_promotion_points import (
    LoyaltyEventAccumulatePromotionPoints,
    LoyaltyEventAccumulatePromotionPointsDict,
)
from .loyalty_event_adjust_points import LoyaltyEventAdjustPoints, LoyaltyEventAdjustPointsDict
from .loyalty_event_create_reward import LoyaltyEventCreateReward, LoyaltyEventCreateRewardDict
from .loyalty_event_delete_reward import LoyaltyEventDeleteReward, LoyaltyEventDeleteRewardDict
from .loyalty_event_expire_points import LoyaltyEventExpirePoints, LoyaltyEventExpirePointsDict
from .loyalty_event_other import LoyaltyEventOther, LoyaltyEventOtherDict
from .loyalty_event_redeem_reward import LoyaltyEventRedeemReward, LoyaltyEventRedeemRewardDict


class LoyaltyEvent(SdkBaseModel):
    """Provides information about a loyalty event. For more information, see `Search for Balance-Changing Loyalty Events
    <https://developer.squareup.com/docs/loyalty-api/loyalty-events>`__."""

    id: str
    """The Square-assigned ID of the loyalty event."""

    type_: LoyaltyEventTypeOrStr = Field(alias="type")
    """The type of the loyalty event."""

    created_at: str
    """The timestamp when the event was created, in RFC 3339 format."""

    accumulate_points: Optional[LoyaltyEventAccumulatePoints] = UNSET
    """Provides metadata when the event ``type`` is ``ACCUMULATE_POINTS``."""

    create_reward: Optional[LoyaltyEventCreateReward] = UNSET
    """Provides metadata when the event ``type`` is ``CREATE_REWARD``."""

    redeem_reward: Optional[LoyaltyEventRedeemReward] = UNSET
    """Provides metadata when the event ``type`` is ``REDEEM_REWARD``."""

    delete_reward: Optional[LoyaltyEventDeleteReward] = UNSET
    """Provides metadata when the event ``type`` is ``DELETE_REWARD``."""

    adjust_points: Optional[LoyaltyEventAdjustPoints] = UNSET
    """Provides metadata when the event ``type`` is ``ADJUST_POINTS``."""

    loyalty_account_id: str
    """The ID of the `loyalty account <entity:LoyaltyAccount>`__ associated with the event."""

    location_id: Optional[str] = UNSET
    """The ID of the `location <entity:Location>`__ where the event occurred."""

    source: LoyaltyEventSourceOrStr
    """Defines whether the event was generated by the Square Point of Sale."""

    expire_points: Optional[LoyaltyEventExpirePoints] = UNSET
    """Provides metadata when the event ``type`` is ``EXPIRE_POINTS``."""

    other_event: Optional[LoyaltyEventOther] = UNSET
    """Provides metadata when the event ``type`` is ``OTHER``."""

    accumulate_promotion_points: Optional[LoyaltyEventAccumulatePromotionPoints] = UNSET
    """Provides metadata when the event ``type`` is ``ACCUMULATE_PROMOTION_POINTS``."""


class LoyaltyEventDict(TypedDict):
    id: str
    type_: LoyaltyEventTypeOrStr
    created_at: str
    accumulate_points: NotRequired[LoyaltyEventAccumulatePointsDict]
    create_reward: NotRequired[LoyaltyEventCreateRewardDict]
    redeem_reward: NotRequired[LoyaltyEventRedeemRewardDict]
    delete_reward: NotRequired[LoyaltyEventDeleteRewardDict]
    adjust_points: NotRequired[LoyaltyEventAdjustPointsDict]
    loyalty_account_id: str
    location_id: NotRequired[str]
    source: LoyaltyEventSourceOrStr
    expire_points: NotRequired[LoyaltyEventExpirePointsDict]
    other_event: NotRequired[LoyaltyEventOtherDict]
    accumulate_promotion_points: NotRequired[LoyaltyEventAccumulatePromotionPointsDict]
