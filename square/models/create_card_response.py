class CreateCardResponse(SdkBaseModel):
    """Defines the fields that are included in the response body of a request to the `CreateCard
    <api-endpoint:Cards-CreateCard>`__ endpoint.

    Note: if there are errors processing the request, the card field will not be present."""

    errors: Optional[list[Error]] = UNSET
    """Errors resulting from the request."""

    card: Optional[Card] = UNSET
    """Represents the payment details of a card to be used for payments. These details are determined by the payment
    token generated by Web Payments SDK."""


class CreateCardResponseDict(TypedDict):
    errors: NotRequired[list[ErrorDict]]
    card: NotRequired[CardDict]
