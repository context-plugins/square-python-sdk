from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .card import Card, CardDict
from .enums.tender_card_details_entry_method import TenderCardDetailsEntryMethodOrStr
from .enums.tender_card_details_status import TenderCardDetailsStatusOrStr


class TenderCardDetails(SdkBaseModel):
    """Represents additional details of a tender with ``type`` ``CARD`` or ``SQUARE_GIFT_CARD``"""

    status: Optional[TenderCardDetailsStatusOrStr] = UNSET
    """Indicates the card transaction's current status."""

    card: Optional[Card] = UNSET
    """Represents the payment details of a card to be used for payments. These details are determined by the payment
    token generated by Web Payments SDK."""

    entry_method: Optional[TenderCardDetailsEntryMethodOrStr] = UNSET
    """Indicates the method used to enter the card's details."""


class TenderCardDetailsDict(TypedDict):
    status: NotRequired[TenderCardDetailsStatusOrStr]
    card: NotRequired[Card | CardDict]
    entry_method: NotRequired[TenderCardDetailsEntryMethodOrStr]
