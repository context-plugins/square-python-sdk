from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .card import Card, CardDict
from .error import Error, ErrorDict


class RetrieveCardResponse(SdkBaseModel):
    """Defines the fields that are included in the response body of a request to the `RetrieveCard
    <api-endpoint:Cards-RetrieveCard>`__ endpoint.

    Note: if there are errors processing the request, the card field will not be present."""

    errors: Optional[list[Error]] = UNSET
    """Information on errors encountered during the request."""

    card: Optional[Card] = UNSET
    """Represents the payment details of a card to be used for payments. These details are determined by the payment
    token generated by Web Payments SDK."""


class RetrieveCardResponseDict(TypedDict):
    errors: NotRequired[list[ErrorDict]]
    card: NotRequired[CardDict]
