from __future__ import annotations

from typing_extensions import NotRequired, TypedDict

from ..core import UNSET, Optional, SdkBaseModel
from .address import Address, AddressDict


class CreateCustomerCardRequest(SdkBaseModel):
    """Defines the fields that are included in the request body of a request to the ``CreateCustomerCard`` endpoint."""

    card_nonce: str
    """A card nonce representing the credit card to link to the customer.

    Card nonces are generated by the Square payment form when customers enter their card information. For more
    information, see `Walkthrough: Integrate Square Payments in a Website
    <https://developer.squareup.com/docs/web-payments/take-card-payment>`__.

    __NOTE:__ Card nonces generated by digital wallets (such as Apple Pay) cannot be used to create a customer card."""

    billing_address: Optional[Address] = UNSET
    """Represents a postal address in a country. For more information, see `Working with Addresses
    <https://developer.squareup.com/docs/build-basics/working-with-addresses>`__."""

    cardholder_name: Optional[str] = UNSET
    """The full name printed on the credit card."""

    verification_token: Optional[str] = UNSET
    """An identifying token generated by `Payments.verifyBuyer()
    <https://developer.squareup.com/reference/sdks/web/payments/objects/Payments#Payments.verifyBuyer>`__. Verification
    tokens encapsulate customer device information and 3-D Secure challenge results to indicate that Square has verified
    the buyer identity."""


class CreateCustomerCardRequestDict(TypedDict):
    card_nonce: str
    billing_address: NotRequired[AddressDict]
    cardholder_name: NotRequired[str]
    verification_token: NotRequired[str]
